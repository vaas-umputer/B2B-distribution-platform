package com.imperial.order.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import org.springframework.data.domain.Persistable;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * Implements Persistable for the same reason as Tenant: the id is assigned
 * in Java (UUID.randomUUID()), not generated by the DB.
 *
 * <p>Two status-like fields on purpose, both reusing OrderStatus:
 * <ul>
 *   <li>{@code status} - the coarse, API-facing lifecycle: PLACED,
 *       COMPLETED, CREDIT_REJECTED, STOCK_REJECTED, ROLLED_BACK. This is
 *       what a dealer dashboard would show.</li>
 *   <li>{@code sagaState} - the fine-grained internal step pointer,
 *       updated after EVERY step (PLACED -> CREDIT_LOCKED -> STOCK_RESERVED
 *       -> INVOICED -> COMPLETED). Nothing public reads this in Phase 2 -
 *       it exists so a crash mid-saga leaves a durable, inspectable trail
 *       of exactly where things stopped, which is what Phase 5's recovery
 *       sweep reads.</li>
 * </ul>
 * The two only ever differ while a saga is mid-flight; once it reaches a
 * terminal state they say the same thing.
 */
@Entity
@Table(name = "orders")
public class OrderEntity implements Persistable<UUID> {

    @Id
    private UUID id;

    @Transient
    private boolean isNew = true;

    @Column(name = "tenant_id")
    private UUID tenantId;

    @Enumerated(EnumType.STRING)
    private OrderStatus status;

    @Enumerated(EnumType.STRING)
    @Column(name = "saga_state")
    private OrderStatus sagaState;

    @Column(name = "total_value")
    private BigDecimal totalValue;

    @Column(name = "idempotency_key")
    private String idempotencyKey;

    @Column(name = "invoice_id")
    private UUID invoiceId;

    @Column(name = "rejection_reason")
    private String rejectionReason;

    @Column(name = "created_at")
    private Instant createdAt;

    protected OrderEntity() {
        // for JPA
    }

    public OrderEntity(UUID id, UUID tenantId, OrderStatus status, BigDecimal totalValue,
                        String idempotencyKey, Instant createdAt) {
        this.id = id;
        this.tenantId = tenantId;
        this.status = status;
        this.sagaState = status;
        this.totalValue = totalValue;
        this.idempotencyKey = idempotencyKey;
        this.createdAt = createdAt;
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    public UUID getTenantId() {
        return tenantId;
    }

    public OrderStatus getStatus() {
        return status;
    }

    public void setStatus(OrderStatus status) {
        this.status = status;
    }

    public OrderStatus getSagaState() {
        return sagaState;
    }

    public void setSagaState(OrderStatus sagaState) {
        this.sagaState = sagaState;
    }

    public BigDecimal getTotalValue() {
        return totalValue;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public UUID getInvoiceId() {
        return invoiceId;
    }

    public void setInvoiceId(UUID invoiceId) {
        this.invoiceId = invoiceId;
    }

    public String getRejectionReason() {
        return rejectionReason;
    }

    public void setRejectionReason(String rejectionReason) {
        this.rejectionReason = rejectionReason;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
