package com.imperial.tenant.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.Table;
import jakarta.persistence.Transient;
import org.springframework.data.domain.Persistable;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * Implements Persistable: the id here is assigned by the app (UUID.randomUUID()
 * in the service layer), not generated by Hibernate/the DB. Without this,
 * Spring Data JPA's save() sees a non-null id on a brand-new instance and
 * assumes it must already exist, calling entityManager.merge() instead of
 * persist() - and merge() always runs a SELECT-by-id first to decide
 * insert vs. update. That extra SELECT, running before any INSERT has
 * happened, is what exposed a second bug: it goes through the same RLS
 * policy as every other read, and for onboarding specifically there's no
 * tenant context yet to satisfy it. isNew() being explicit here means
 * save() always calls persist() for a freshly-constructed entity - no
 * extra SELECT, no RLS evaluation, no ambiguity.
 */
@Entity
@Table(name = "tenants")
public class Tenant implements Persistable<UUID> {

    @Id
    private UUID id;

    @Transient
    private boolean isNew = true;

    private String name;
    private String username;
    @Column(name = "password_hash") private String passwordHash;
    private String email;
    private String phone;

    @Enumerated(EnumType.STRING)
    private TenantStatus status;

    @Column(name = "credit_limit")
    private BigDecimal creditLimit;

    @Column(name = "risk_score")
    private Integer riskScore;

    @Column(name = "created_at")
    private Instant createdAt;

    protected Tenant() {
        // for JPA
    }

    public Tenant(UUID id, String name, String username, String passwordHash, String email, String phone, TenantStatus status, Instant createdAt) {
        this.id = id;
        this.name = name;
        this.username = username;
        this.passwordHash = passwordHash;
        this.email = email;
        this.phone = phone;
        this.status = status;
        this.createdAt = createdAt;
    }

    @Override
    public UUID getId() {
        return id;
    }

    @Override
    public boolean isNew() {
        return isNew;
    }

    @PostLoad
    @PostPersist
    void markNotNew() {
        this.isNew = false;
    }

    public String getName() {
        return name;
    }

    public TenantStatus getStatus() {
        return status;
    }
    public String getUsername() { return username; }
    public String getPasswordHash() { return passwordHash; }
    public String getEmail() { return email; }
    public String getPhone() { return phone; }

    public BigDecimal getCreditLimit() {
        return creditLimit;
    }

    public Integer getRiskScore() {
        return riskScore;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
